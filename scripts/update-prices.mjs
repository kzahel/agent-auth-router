#!/usr/bin/env node
// Regenerates src/prices-data.ts from the pinned genai-prices reference
// checkout (reference/pins.toml). Keeps the Anthropic and OpenAI sections and
// only the price fields the router can price from its stored usage; see
// docs/pricing.md. Run `python3 scripts/references.py sync --only
// genai-prices` first, then review the diff like any source change.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const checkout = join(root, "reference/genai-prices");
const PROVIDERS = ["anthropic", "openai"];
const PRICE_KEYS = ["input_mtok", "cache_read_mtok", "cache_write_mtok", "cache_write_1h_mtok", "output_mtok", "web_searches_kcount"];
// Request context the router records; batch and other variants never apply to routed traffic.
const VARIANT_KEYS = ["service_tier"];

const git = (...args) => execFileSync("git", ["-C", checkout, ...args], { encoding: "utf8" }).trim();
const commit = git("rev-parse", "HEAD");
const date = git("show", "-s", "--format=%cs", "HEAD");
if (git("status", "--porcelain")) throw new Error("reference/genai-prices has local changes");
const license = readFileSync(join(checkout, "LICENSE"), "utf8").trim();
const data = JSON.parse(readFileSync(join(checkout, "prices/new_data/v2/data.json"), "utf8"));

const trimPrices = (prices) => Object.fromEntries(PRICE_KEYS.filter((key) => prices[key] !== undefined).map((key) => [key, prices[key]]));
function constraint(value, model) {
  if (value === undefined || value === null) return undefined;
  if (Object.keys(value).length === 1 && typeof value.start_date === "string") return { start_date: value.start_date };
  throw new Error(`${model}: unsupported price constraint ${JSON.stringify(value)}`);
}

const providers = PROVIDERS.map((id) => {
  const provider = data.find((p) => p.id === id);
  if (!provider) throw new Error(`provider ${id} missing`);
  return {
    id,
    models: provider.models.map((model) => {
      const prices = Array.isArray(model.prices)
        ? model.prices.map((p) => ({ ...(constraint(p.constraint, model.id) ? { constraint: constraint(p.constraint, model.id) } : {}), prices: trimPrices(p.prices) }))
        : trimPrices(model.prices);
      const variants = (model.price_variants ?? [])
        .filter((v) => Object.keys(v.when).every((key) => VARIANT_KEYS.includes(key)))
        .map((v) => ({ when: v.when, prices: trimPrices(v.prices), ...(constraint(v.constraint, model.id) ? { constraint: constraint(v.constraint, model.id) } : {}) }));
      return { id: model.id, match: model.match, prices, ...(variants.length ? { price_variants: variants } : {}) };
    }),
  };
});

const header = `// Generated by scripts/update-prices.mjs; do not edit. API prices in USD per
// million tokens (per thousand for web searches) from pydantic/genai-prices
// ${commit} (${date}), prices/new_data/v2/data.json,
// trimmed to the Anthropic and OpenAI fields the router prices.
//
${license.split("\n").map((line) => `// ${line}`.trimEnd()).join("\n")}

import type { PriceProvider } from "./pricing.ts";

export const PRICES_SOURCE = ${JSON.stringify({ repository: "https://github.com/pydantic/genai-prices", commit, date })} as const;

export const PRICE_PROVIDERS: PriceProvider[] = ${JSON.stringify(providers, null, 1)};
`;
writeFileSync(join(root, "src/prices-data.ts"), header);
console.log(`src/prices-data.ts: ${providers.map((p) => `${p.id} ${p.models.length} models`).join(", ")} from ${commit.slice(0, 10)} (${date})`);
